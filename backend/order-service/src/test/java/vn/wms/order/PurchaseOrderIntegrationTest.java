    @Test
    void createPurchaseOrderSuccessfullyWithAutoGeneratedPoNumberAndCalculations() throws Exception {
        Supplier supplier = createSampleSupplier("SUP-CALC", "Công ty Sữa Vinamilk");

        // Dòng 1: qty = 100, unitPrice = 50,000 -> raw = 5,000,000
        // Chiết khấu 10% = 500,000 -> net = 4,500,000
        // VAT 8% = 360,000 -> lineTotal = 4,860,000
        PurchaseOrderItemRequest item1 = new PurchaseOrderItemRequest(
                1L, "SKU-MILK-01", "Sữa tươi có đường 180ml", "Thùng",
                new BigDecimal("100.000"), new BigDecimal("50000.00"),
                new BigDecimal("10.00"), null,
                new BigDecimal("8.00"), null,
                "Lô sản xuất mới"
        );

        // Dòng 2: qty = 50, unitPrice = 200,000 -> raw = 10,000,000
        // Không chiết khấu (0%) -> net = 10,000,000
        // VAT 10% = 1,000,000 -> lineTotal = 11,000,000
        PurchaseOrderItemRequest item2 = new PurchaseOrderItemRequest(
                2L, "SKU-YOGURT-02", "Sữa chua nếp cẩm", "Thùng",
                new BigDecimal("50.000"), new BigDecimal("200000.00"),
                BigDecimal.ZERO, null,
                new BigDecimal("10.00"), null,
                null
        );

        CreatePurchaseOrderRequest request = new CreatePurchaseOrderRequest(
                null, // Bỏ trống mã PO để hệ thống tự sinh PO-YYYYMMDD-XXXX
                supplier.getId(),
                10L,
                "Kho Tổng Tân Bình",
                LocalDate.now(),
                LocalDate.now().plusDays(7),
                "Đơn nhập hàng phục vụ đợt khuyến mãi",
                OrderStatus.PENDING,
                List.of(item1, item2)
        );

        // Grand Total dự kiến = 4,860,000 + 11,000,000 = 15,860,000
        // Subtotal = 15,000,000, Discount = 500,000, Tax = 1,360,000
        mockMvc.perform(post("/api/orders/purchase")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.poNumber").isNotEmpty())
                .andExpect(jsonPath("$.data.status").value("PENDING"))
                .andExpect(jsonPath("$.data.warehouseName").value("Kho Tổng Tân Bình"))
                .andExpect(jsonPath("$.data.subtotalAmount").value(15000000.00))
                .andExpect(jsonPath("$.data.discountAmount").value(500000.00))
                .andExpect(jsonPath("$.data.taxAmount").value(1360000.00))
                .andExpect(jsonPath("$.data.totalAmount").value(15860000.00))
                .andExpect(jsonPath("$.data.items").isArray())
                .andExpect(jsonPath("$.data.items.length()").value(2))
                .andExpect(jsonPath("$.data.items[0].lineTotal").value(4860000.00))
                .andExpect(jsonPath("$.data.items[1].lineTotal").value(11000000.00));

        // Kiểm tra lưu DB
        List<PurchaseOrder> all = purchaseOrderRepository.findAll();
        assertThat(all).anyMatch(po -> po.getTotalAmount().compareTo(new BigDecimal("15860000.00")) == 0);
    }

