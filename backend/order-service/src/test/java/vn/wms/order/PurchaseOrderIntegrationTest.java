    @Test
    void approvePurchaseOrderWorkflow() throws Exception {
        Supplier supplier = createSampleSupplier("SUP-APP", "Công ty CP Dược Phẩm");

        PurchaseOrderItemRequest item = new PurchaseOrderItemRequest(
                null, "SKU-MED-01", "Khẩu trang y tế 4 lớp", "Hộp",
                new BigDecimal("200.000"), new BigDecimal("25000.00"),
                null, null, null, null, null
        );

        CreatePurchaseOrderRequest createReq = new CreatePurchaseOrderRequest(
                null, supplier.getId(), 1L, "Kho Dược",
                LocalDate.now(), null, null,
                OrderStatus.PENDING,
                List.of(item)
        );

        // Tạo đơn
        String resStr = mockMvc.perform(post("/api/orders/purchase")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(createReq)))
                .andExpect(status().isCreated())
                .andReturn().getResponse().getContentAsString();

        Long orderId = objectMapper.readTree(resStr).path("data").path("id").asLong();

        // Phê duyệt đơn mua với header X-User-Name
        mockMvc.perform(post("/api/orders/purchase/" + orderId + "/approve")
                        .header("X-User-Name", "quanlykho"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("APPROVED"))
                .andExpect(jsonPath("$.data.approvedBy").value("quanlykho"))
                .andExpect(jsonPath("$.data.approvedAt").isNotEmpty());

        // Kiểm tra duyệt lại bị từ chối 400 Bad Request
        mockMvc.perform(post("/api/orders/purchase/" + orderId + "/approve"))
                .andExpect(status().isBadRequest());
    }

