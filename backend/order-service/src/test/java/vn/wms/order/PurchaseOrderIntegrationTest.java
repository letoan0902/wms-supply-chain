    @Test
    void searchAndFilterPurchaseOrders() throws Exception {
        Supplier s1 = createSampleSupplier("SUP-FLT1", "Nhà cung cấp 1");
        Supplier s2 = createSampleSupplier("SUP-FLT2", "Nhà cung cấp 2");

        PurchaseOrderItemRequest item1 = new PurchaseOrderItemRequest(
                null, "SKU-FLT-1", "Hàng 1", "Cái",
                new BigDecimal("10.000"), new BigDecimal("10000.00"),
                null, null, null, null, null
        );

        PurchaseOrderItemRequest item2 = new PurchaseOrderItemRequest(
                null, "SKU-FLT-2", "Hàng 2", "Cái",
                new BigDecimal("20.000"), new BigDecimal("15000.00"),
                null, null, null, null, null
        );

        CreatePurchaseOrderRequest po1 = new CreatePurchaseOrderRequest(
                "PO-FLT-001", s1.getId(), 10L, "Kho 1",
                LocalDate.of(2026, 11, 1), null, "Đơn đợt 1", OrderStatus.PENDING, List.of(item1)
        );

        CreatePurchaseOrderRequest po2 = new CreatePurchaseOrderRequest(
                "PO-FLT-002", s2.getId(), 20L, "Kho 2",
                LocalDate.of(2026, 11, 2), null, "Đơn đợt 2", OrderStatus.DRAFT, List.of(item2)
        );

        mockMvc.perform(post("/api/orders/purchase").contentType(MediaType.APPLICATION_JSON).content(objectMapper.writeValueAsString(po1))).andExpect(status().isCreated());
        mockMvc.perform(post("/api/orders/purchase").contentType(MediaType.APPLICATION_JSON).content(objectMapper.writeValueAsString(po2))).andExpect(status().isCreated());

        // Lọc theo keyword
        mockMvc.perform(get("/api/orders/purchase").param("keyword", "PO-FLT-001"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.totalElements").value(1))
                .andExpect(jsonPath("$.data.content[0].poNumber").value("PO-FLT-001"));

        // Lọc theo status = DRAFT
        mockMvc.perform(get("/api/orders/purchase").param("status", "DRAFT"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.content[?(@.poNumber == 'PO-FLT-002')]").exists());
    }

